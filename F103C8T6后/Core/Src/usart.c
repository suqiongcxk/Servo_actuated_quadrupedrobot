void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{

    if (huart==&huart1)//RS485
    {
				HAL_UART_DMAStop(&huart1); // 此时安全
        memcpy(RS485_dma_buffer, RS485_rx_dma_buffer,Size);       
		
        RS485_flag = 1;       

        memset(RS485_rx_dma_buffer, 0, 60); // sizeof(RS485_rx_dma_buffer)
//      for (int i = 0;i <50 ;i++)
//			{
//			printf("%X ",RS485_dma_buffer[i]);
//			}
//			printf("\n");		
			
			HAL_UARTEx_ReceiveToIdle_DMA(&huart1, RS485_rx_dma_buffer, sizeof(RS485_rx_dma_buffer));
      		if (RS485RXHandle != NULL)
    {        
			
			
		  BaseType_t xHigherPriorityTaskWoken = pdFALSE; // 初始化为pdFALSE
      // 传入变量地址，让函数标记是否需要切换			
			xSemaphoreGiveFromISR(RS485RXHandle, &xHigherPriorityTaskWoken);
			// 触发上下文切换：如果xHigherPriorityTaskWoken为pdTRUE，就立刻切换
      portYIELD_FROM_ISR(xHigherPriorityTaskWoken);
			
			
    }
    }
		
		if(huart==&huart3)//串口3
    {
					if(USART3_flag == 0)//解析完成一段
					{
						HAL_UART_DMAStop(&huart3); // 此时安全
						memcpy(USART3_dma_buffer, USART3_rx_dma_buffer,30);	
						USART3_flag=1;
					}
        memset(USART3_rx_dma_buffer, 0, sizeof(USART3_rx_dma_buffer));

			HAL_UARTEx_ReceiveToIdle_DMA(&huart3, USART3_rx_dma_buffer, sizeof(USART3_rx_dma_buffer));
    }
		
		
}
